"""Pydantic schemas for geographic locations and withdrawal forecasts."""

from datetime import datetime
from typing import Optional
from pydantic import BaseModel, Field, ConfigDict


class LocationResponse(BaseModel):
    """Geographic coordinate representation for mapping and geospatial analysis."""

    model_config = ConfigDict(from_attributes=True)

    id: int = Field(description="Location database ID")
    case_id: Optional[int] = Field(default=None, description="Optional associated case ID")
    name: str = Field(description="Descriptive location name")
    location_type: str = Field(
        description="Type: 'reported', 'candidate_withdrawal', 'atm', 'branch', 'pos'"
    )
    address: str = Field(default="", description="Street or area address")
    district: str = Field(description="District / city name")
    state: str = Field(description="State or region name")
    latitude: float = Field(ge=-90.0, le=90.0, description="WGS84 Latitude")
    longitude: float = Field(ge=-180.0, le=180.0, description="WGS84 Longitude")
    risk_score: float = Field(ge=0.0, le=1.0, description="Assessed risk score between 0.0 and 1.0")
    is_predicted: bool = Field(description="True if generated by predictive model; False if reported origin")
    confidence: float = Field(ge=0.0, le=1.0, description="Model prediction confidence score")
    disclaimer: str = Field(
        default="Predicted candidate location only - not confirmed cash withdrawal or proof of criminal activity.",
        description="Mandatory investigative disclaimer",
    )
    created_at: datetime = Field(description="Record creation timestamp")
