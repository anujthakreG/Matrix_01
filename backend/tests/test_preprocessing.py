def test_preprocessing_steps_on_50_row_fixture(synthetic_50_row_fixture: pd.DataFrame, caplog: pytest.LogCaptureFixture):
    """
    Verify complete batch preprocessing pipeline on the 50-row fixture:
    - Deduplication
    - Missing value imputation
    - Invalid amount (<=0) clipping (clip, don't silently drop)
    - Outlier clipping (clip, don't silently drop)
    - Invalid timestamp handling
    - Inconsistent casing/spelling normalization
    - Verify logging reports row counts for each step.
    """
    df = synthetic_50_row_fixture.copy()

    # Manually inject controlled dirty records to test all edge cases
    # 1. Inject duplicate row
    dup_row = df.iloc[0].copy()
    # 2. Inject non-positive amount (<= 0)
    invalid_amount_row = df.iloc[1].copy()
    invalid_amount_row["complaint_id"] = "SYN-DIRTY-001"
    invalid_amount_row["reported_amount"] = -500.0
    # 3. Inject extreme outlier amount
    outlier_amount_row = df.iloc[2].copy()
    outlier_amount_row["complaint_id"] = "SYN-DIRTY-002"
    outlier_amount_row["reported_amount"] = 50_000_000.0  # Exceeds MAX_AMOUNT_LIMIT
    # 4. Inject invalid timestamp
    invalid_ts_row = df.iloc[3].copy()
    invalid_ts_row["complaint_id"] = "SYN-DIRTY-003"
    invalid_ts_row["incident_time"] = "INVALID_NOT_A_DATE"
    # 5. Inject missing values
    missing_fields_row = df.iloc[4].copy()
    missing_fields_row["complaint_id"] = "SYN-DIRTY-004"
    missing_fields_row["victim_district"] = None
    missing_fields_row["source_channel"] = None

    dirty_df = pd.concat([df, pd.DataFrame([dup_row, invalid_amount_row, outlier_amount_row, invalid_ts_row, missing_fields_row])], ignore_index=True)

    with caplog.at_level(logging.INFO):
        cleaned_df = clean_and_normalize_complaints(dirty_df)

    # Step 1: Duplicates removed (deduplication)
    assert len(cleaned_df) < len(dirty_df)
    assert "Step 1 (Deduplication): Removed" in caplog.text

    # Step 2: Missing values imputed (zero NaNs in feature columns)
    assert cleaned_df[config.COL_VICTIM_DISTRICT].isna().sum() == 0
    assert cleaned_df[config.COL_SOURCE_CHANNEL].isna().sum() == 0
    assert "Step 2 (Missing Values): Imputed missing fields" in caplog.text

    # Step 3: Non-positive amounts clipped to MIN_POSITIVE_AMOUNT (never dropped)
    assert (cleaned_df[config.COL_REPORTED_AMOUNT] <= 0).sum() == 0
    assert (cleaned_df[config.COL_REPORTED_AMOUNT] >= config.MIN_POSITIVE_AMOUNT).all()
    assert "Step 3 (Invalid Amounts): Clipped" in caplog.text

    # Step 4: Outlier amounts clipped to MAX_AMOUNT_LIMIT (never dropped)
    assert (cleaned_df[config.COL_REPORTED_AMOUNT] > config.MAX_AMOUNT_LIMIT).sum() == 0
    assert config.COL_AMOUNT_LOG in cleaned_df.columns
    assert "Step 4 (Outliers): Clipped" in caplog.text

    # Step 5: Timestamps parsed and features derived
    assert config.COL_HOUR in cleaned_df.columns
    assert config.COL_WEEKDAY in cleaned_df.columns
    assert config.COL_IS_NIGHT in cleaned_df.columns
    assert config.COL_IS_WEEKEND in cleaned_df.columns
    assert "Step 5 (Timestamps): Imputed" in caplog.text

    # Step 6: Text casing normalized
    assert "Step 6 (Casing & Spelling): Normalized categories" in caplog.text

    # Strict rule: Target column is preserved and uncorrupted
    assert cleaned_df[config.TARGET_COLUMN].isna().sum() == 0


def test_synthetic_cli_and_force_flag(tmp_path: Path):
    """Verify synthetic generator CLI execution and overwrite protection."""
    out_file = tmp_path / "cli_generated.csv"

    # 1. Initial generation succeeds
    ret = synthetic_main(["--rows", "50", "--seed", "123", "--output", str(out_file)])
    assert ret == 0
    assert out_file.exists()

    # 2. Overwrite without --force fails cleanly
    ret_fail = synthetic_main(["--rows", "50", "--seed", "123", "--output", str(out_file)])
    assert ret_fail == 1

    # 3. Overwrite with --force succeeds
    ret_force = synthetic_main(["--rows", "60", "--seed", "123", "--output", str(out_file), "--force"])
    assert ret_force == 0
    df = pd.read_csv(out_file)
    assert len(df) == 60
