"""
Tests for feature extraction and pipeline transformations.
Uses a 50-row fixture generated by synthetic.py with fixed seed=42.
Ensures zero target leakage and strict train-only fitting for encoders.
"""

import pandas as pd
import pytest

from backend.app.ml.config import config
from backend.app.ml.preprocessing import clean_and_normalize_complaints
from backend.app.ml.features import extract_raw_feature_matrix, build_feature_transformer
from backend.app.ml.synthetic import generate_synthetic_complaints


@pytest.fixture
def synthetic_50_row_fixture() -> pd.DataFrame:
    """Deterministic 50-row test fixture generated by synthetic.py with fixed seed=42."""
    return generate_synthetic_complaints(num_rows=50, seed=42)


def test_feature_matrix_schema_and_inference_alignment(synthetic_50_row_fixture: pd.DataFrame):
    """
    Verify feature matrix extraction:
    - Extracts: hour, weekday, is_night, is_weekend, log_amount, mule_hop_count
    - Extracts: category, victim_state, victim_district, source_channel
    - Guarantees target column is NEVER in feature matrix
    - Guarantees unobservable features are absent
    """
    cleaned_df = clean_and_normalize_complaints(synthetic_50_row_fixture)
    features = extract_raw_feature_matrix(cleaned_df)

    # 1. Check exact expected columns
    expected_cols = config.NUMERICAL_FEATURES + config.CATEGORICAL_FEATURES
    assert list(features.columns) == expected_cols

    # 2. Verify all numerical features requested
    assert "hour" in features.columns
    assert "weekday" in features.columns
    assert "is_night" in features.columns
    assert "is_weekend" in features.columns
    assert "log_amount" in features.columns
    assert "mule_hop_count" in features.columns

    # 3. Verify all categoricals
    assert "category" in features.columns
    assert "victim_state" in features.columns
    assert "victim_district" in features.columns
    assert "source_channel" in features.columns

    # 4. Strict rule: No feature may use the target
    assert config.TARGET_COLUMN not in features.columns
    assert "withdrawal_district" not in features.columns
    assert "withdrawal_state" not in features.columns
    assert "withdrawal_lat" not in features.columns
    assert "withdrawal_lon" not in features.columns

    # 5. Strict rule: Exclude unobservable inference features
    assert "bank_code" not in features.columns
    assert "reporting_delay_hours" not in features.columns
    assert "suspect_bank" not in features.columns
    assert "withdrawal_window_hours" not in features.columns


def test_feature_transformer_fit_on_train_only(synthetic_50_row_fixture: pd.DataFrame):
    """
    Verify that the transformer pipeline is fitted on TRAIN ONLY
    and transforms test data with unseen entities without raising errors.
    """
    cleaned_df = clean_and_normalize_complaints(synthetic_50_row_fixture)
    features = extract_raw_feature_matrix(cleaned_df)

    # Split into 70% train and 30% test
    n_train = int(len(features) * 0.70)
    train_features = features.iloc[:n_train]
    test_features = features.iloc[n_train:]

    transformer = build_feature_transformer()

    # Fit strictly on train features
    transformer.fit(train_features)

    # Transform both train and test
    X_train_trans = transformer.transform(train_features)
    X_test_trans = transformer.transform(test_features)

    assert X_train_trans.shape[0] == len(train_features)
    assert X_test_trans.shape[0] == len(test_features)
    assert X_train_trans.shape[1] == X_test_trans.shape[1]

    # Test transforming completely out-of-vocabulary test sample
    unseen_sample = pd.DataFrame([{
        "hour": 3,
        "weekday": 6,
        "is_night": 1,
        "is_weekend": 1,
        "log_amount": 11.2,
        "mule_hop_count": 4,
        "category": "completely_unseen_cat",
        "victim_state": "CompletelyUnseenState",
        "victim_district": "CompletelyUnseenDistrict",
        "source_channel": "UNSEEN_CHANNEL",
    }])
    X_unseen_trans = transformer.transform(unseen_sample)
    assert X_unseen_trans.shape[0] == 1
    assert X_unseen_trans.shape[1] == X_train_trans.shape[1]
